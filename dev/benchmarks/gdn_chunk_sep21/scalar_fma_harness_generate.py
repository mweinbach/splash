"""Generate a separate staged explicit-FMA synthetic oracle; no GPU work."""
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
CASES = [
    ("v8_t8", 8, 8),
    ("v8_t16", 8, 16),
    ("v16_t8", 16, 8),
    ("v16_t16", 16, 16),
    ("v16_t32", 16, 32),
    ("dot_v16_t16", 16, 16),
    ("update_v16_t16", 16, 16),
]
source = (HERE / "metal_oracle.mm").read_text()
variants = "constexpr std::array<Variant, %d> Variants{{\n" % len(CASES)
variants += ",\n".join(
    '    {"private_gdn_scalar_fma_%s", %d, %d}' % (name, values, time)
    for name, values, time in CASES
) + "}};"
source, n = re.subn(r"constexpr std::array<Variant, 5> Variants\{\{.*?\}\};",
                    variants, source, flags=re.S)
assert n == 1
audit = '''std::string auditName(const Variant &variant) {
    std::string name = variant.name;
    const auto where = name.rfind("_v");
    require(where != std::string::npos, "unknown scalar FMA variant");
    name.replace(where, 2, "_audit_v");
    return name;
}'''
source, n = re.subn(r"std::string auditName\(const Variant &variant\) \{.*?\n\}",
                    audit, source, count=1, flags=re.S)
assert n == 1
source = source.replace(
    'const unsigned threads = std::string(variant.name) == Canonical.name ? 512 : 128;',
    'const unsigned threads = variant.values * 32;')
assert 'const unsigned threads = variant.values * 32;' in source
assert source.count("gdn-chunk.metallib") == 1
source = source.replace("gdn-chunk.metallib", "gdn-scalar-fma.metallib")
(HERE / "metal_oracle_scalar_fma.mm").write_text(
    "// Generated by scalar_fma_harness_generate.py; originals remain frozen.\n" + source
)
