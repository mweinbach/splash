"""Generate isolated harness copies for the bounded T8 / bank-stride sweep."""
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
CASES = [
    ("v8_t8_p0", 8, 8),
    ("v16_t8_p0", 16, 8),
    ("v16_t8_p1", 16, 8),
    ("v8_t16_p1", 8, 16),
    ("v16_t16_p1", 16, 16),
    ("v16_t16_p4", 16, 16),
    ("register_v32_t8_p0", 32, 8),
    ("register_v32_t8_p1", 32, 8),
]

def generate(source_name, destination_name, prefix, library_name, prepared):
    source = (HERE / source_name).read_text()
    variants = "constexpr std::array<Variant, %d> Variants{{\n" % len(CASES)
    variants += ",\n".join(
        '    {"%s_%s", %d, %d}' % (prefix, name, values, time)
        for name, values, time in CASES
    ) + "}};"
    source, changed = re.subn(
        r"constexpr std::array<Variant, 5> Variants\{\{.*?\}\};",
        variants, source, flags=re.S,
    )
    assert changed == 1
    audit = '''std::string auditName(const Variant &variant) {
    std::string name = variant.name;
    const auto where = name.find("_register_v");
    if (where != std::string::npos) name.replace(where, 11, "_register_audit_v");
    else {
        const auto value = name.find("_occupancy_v");
        require(value != std::string::npos, "unknown occupancy variant");
        name.replace(value, 12, "_occupancy_audit_v");
    }
    return name;
}'''
    source, changed = re.subn(r"std::string auditName\(const Variant &variant\) \{.*?\n\}",
                             audit, source, count=1, flags=re.S)
    assert changed == 1
    old_library = "gdn-chunk-prepared.metallib" if prepared else "gdn-chunk.metallib"
    assert source.count(old_library) == 1
    source = source.replace(old_library, library_name)
    if prepared:
        source = source.replace("private_gdn_chunk_prepare_t", "private_gdn_occupancy_prepare_t")
        source = source.replace("{16u, 32u}", "{8u, 16u}").replace("{16, 32}", "{8, 16}")
    (HERE / destination_name).write_text(
        "// Generated by occupancy_harness_generate.py; original harnesses remain frozen.\n" + source
    )

generate("metal_oracle.mm", "metal_oracle_occupancy.mm", "private_gdn_occupancy",
         "gdn-occupancy.metallib", False)
generate("metal_oracle_prepared.mm", "metal_oracle_prepared_occupancy.mm",
         "private_gdn_prepared_occupancy", "gdn-prepared-occupancy.metallib", True)
