#!/usr/bin/env python3
"""Generate isolated padded/small-tile variants; never modifies frozen sources."""
from pathlib import Path

BASE = Path(__file__).resolve().parent
NORMAL = [(8, 8, 0), (16, 8, 0), (16, 8, 1), (8, 16, 1), (16, 16, 1), (16, 16, 4)]
REGISTER = [(32, 8, 0), (32, 8, 1)]


def generate(prepared: bool) -> None:
    original = 'prepared.metal' if prepared else 'candidate.metal'
    source = (BASE / original).read_text()
    old = 'GDP' if prepared else 'GDC'
    new = 'GPO' if prepared else 'GDO'
    helper = 'gpo' if prepared else 'gdo'
    prefix = 'private_gdn_prepared_occupancy' if prepared else 'private_gdn_occupancy'
    source = source[:source.index(f'#define {old}_MEMORY')]
    source = source.replace('gdp_' if prepared else 'gdc_', helper + '_')
    source = source.replace(
        'template <ushort Values, ushort Time, bool Audit, bool Cached = false>',
        'template <ushort Values, ushort Time, bool Audit, bool Cached = false, ushort Padding = 0>')
    source = source.replace(
        '  auto dt = tensor(delta, dextents<int, 2>{Time, Values}, array<int, 2>{1, Time});',
        '  constexpr ushort MatmulTime = Time < 16 ? 16 : Time;\n'
        '  constexpr ushort MatmulValues = Values < 16 ? 16 : Values;\n'
        '  constexpr int MatmulK = Time < 16 ? static_cast<int>(dynamic_extent) : Time;\n'
        '  constexpr ushort DeltaStride = Time + Padding;\n'
        '  static_assert(Padding == 0 || Padding == 1 || Padding == 4);\n'
        '  auto dt = tensor(delta, dextents<int, 2>{Time, Values}, array<int, 2>{1, DeltaStride});')
    for tensor_name, index in [
        ('delta', 'v * Time + token'),
        ('delta', 'tid * Time + token'),
        ('delta', 'tid * Time + previous'),
        ('delta', 'v * Time + previous'),
        ('stateQuery', '(cachedValueBegin + index[1]) * Time + index[0]'),
        ('stateQuery', 'index[1] * Time + index[0]'),
        ('stateQuery', 'v * Time + token'),
    ]:
        source = source.replace(f'{tensor_name}[{index}]',
                                f'{tensor_name}[{index.replace("* Time", "* DeltaStride")}]')
    source = source.replace('      delta[i] *= product;',
                            '      const uint v = i / Time;\n'
                            '      delta[v * DeltaStride + token] *= product;')
    # MPP requires one output axis divisible by 16, and static inner K by 16.
    # Sources retain true tensor extents; the wider descriptor pads reads and
    # all cooperative-result stores below discard padded output coordinates.
    source = source.replace('matmul2d_descriptor(Time, Time, 128,',
                            'matmul2d_descriptor(Time < 16 ? 16 : Time, Time < 16 ? 16 : Time, 128,')
    source = source.replace('matmul2d_descriptor(Values, Time, 128,',
                            'matmul2d_descriptor(MatmulValues, MatmulTime, 128,')
    source = source.replace('matmul2d_descriptor(Values, Time, Time,',
                            'matmul2d_descriptor(MatmulValues, MatmulTime, MatmulK,')
    source = source.replace('matmul2d_descriptor(Values, 128, Time,',
                            'matmul2d_descriptor(MatmulValues, 128, MatmulK,')
    source = source.replace('matmul2d_descriptor(Values / 4, Time, 128,',
                            'matmul2d_descriptor(Values / 4, MatmulTime, 128,')
    source = source.replace('matmul2d_descriptor(Values / 4, 128, Time,',
                            'matmul2d_descriptor(Values / 4, 128, MatmulK,')
    import re
    guarded_lines = []
    operation = ''
    for line in source.splitlines(keepends=True):
        cooperative_loop = re.search(r'for \(ushort i = 0; i < (\w+)\.get_capacity\(\)', line)
        if cooperative_loop:
            operation = cooperative_loop.group(1)
        guarded_lines.append(line)
        if 'const auto index = ' in line:
            indentation = line[:len(line) - len(line.lstrip())]
            if operation in ['kk', 'qk']:
                guarded_lines.append(indentation + 'if (index[0] >= Time || index[1] >= Time) continue;\n')
            elif operation in ['sk', 'sq', 'result']:
                guarded_lines.append(indentation + 'if (index[0] >= Time || index[1] >= Values) continue;\n')
            elif operation == 'update':
                guarded_lines.append(indentation + 'if (index[1] >= Values) continue;\n')
    source = ''.join(guarded_lines)
    if prepared:
        source = source.replace('private_gdn_chunk_prepare_t##T', 'private_gdn_occupancy_prepare_t##T')
        source = source.replace('GDP_PREPARE_ENTRY', 'GPO_PREPARE_ENTRY')
        source = source.replace('GPO_PREPARE_ENTRY(16)', 'GPO_PREPARE_ENTRY(8)\nGPO_PREPARE_ENTRY(16)')
    source = (
        '// Generated by generate_occupancy.py from ' + original + '.\n'
        '// Isolated occupancy/bank-conflict experiment: delta and stateQuery\n'
        '// rows use Time+Padding F32 stride. Odd stride distributes value lanes\n'
        '// over the 32 banks; unpadded Time16/32 uses only two/one banks.\n'
        '// Gram/score layout and F32 recurrence formulas remain unchanged.\n' + source)
    coefficient_arg = ', device const float *coefficients [[buffer(10)]]' if prepared else ''
    coefficient_pass = ',coefficients' if prepared else ''
    source += f'''#define {new}_MEMORY(V,T,P,S) \\
  threadgroup bfloat keys[T * 128]; \\
  threadgroup float state[S], gram[T * T], score[T * T]; \\
  threadgroup float delta[V * (T + P)], stateQuery[V * (T + P)]; \\
  threadgroup float alphas[T], betas[T], prefix[T];
#define {new}_ARGS \\
  device const bfloat *mixed [[buffer(0)]], device const float *decay [[buffer(1)]], \\
  device const bfloat *beta [[buffer(2)]], device float *recurrent [[buffer(3)]], \\
  device bfloat *output [[buffer(4)]], device atomic_uint &diagnostics [[buffer(5)]], \\
  constant FlashGDNParams &p [[buffer(6)]]{coefficient_arg}
#define {new}_THREADS \\
  uint3 group [[threadgroup_position_in_grid]], uint3 threads [[threads_per_threadgroup]], \\
  uint tid [[thread_index_in_threadgroup]]
#define {new}_ENTRY(V,T,P) \\
  [[max_total_threads_per_threadgroup(128)]] kernel void {prefix}_v##V##_t##T##_p##P( \\
      {new}_ARGS, {new}_THREADS) {{ \\
    {new}_MEMORY(V,T,P,V*128) \\
    {helper}_chunked<V,T,false,false,P>(mixed,decay,beta,recurrent,output,diagnostics,p,group,threads,tid, \\
        keys,state,gram,score,delta,stateQuery,alphas,betas,prefix,nullptr,nullptr,nullptr{coefficient_pass}); \\
  }} \\
  [[max_total_threads_per_threadgroup(128)]] kernel void {prefix}_audit_v##V##_t##T##_p##P( \\
      {new}_ARGS, device float *history [[buffer(7)]], device float *deltaAudit [[buffer(8)]], \\
      device float *outputAudit [[buffer(9)]], {new}_THREADS) {{ \\
    {new}_MEMORY(V,T,P,V*128) \\
    {helper}_chunked<V,T,true,false,P>(mixed,decay,beta,recurrent,output,diagnostics,p,group,threads,tid, \\
        keys,state,gram,score,delta,stateQuery,alphas,betas,prefix,history,deltaAudit,outputAudit{coefficient_pass}); \\
  }}
'''
    source += ''.join(f'{new}_ENTRY({v},{t},{p})\n' for v, t, p in NORMAL)
    source += f'''#define {new}_REGISTER_ENTRY(V,T,P) \\
  [[max_total_threads_per_threadgroup(128)]] kernel void {prefix}_register_v##V##_t##T##_p##P( \\
      {new}_ARGS, {new}_THREADS) {{ \\
    {new}_MEMORY(V,T,P,1) \\
    {helper}_chunked<V,T,false,true,P>(mixed,decay,beta,recurrent,output,diagnostics,p,group,threads,tid, \\
        keys,state,gram,score,delta,stateQuery,alphas,betas,prefix,nullptr,nullptr,nullptr{coefficient_pass}); \\
  }} \\
  [[max_total_threads_per_threadgroup(128)]] kernel void {prefix}_register_audit_v##V##_t##T##_p##P( \\
      {new}_ARGS, device float *history [[buffer(7)]], device float *deltaAudit [[buffer(8)]], \\
      device float *outputAudit [[buffer(9)]], {new}_THREADS) {{ \\
    {new}_MEMORY(V,T,P,1) \\
    {helper}_chunked<V,T,true,true,P>(mixed,decay,beta,recurrent,output,diagnostics,p,group,threads,tid, \\
        keys,state,gram,score,delta,stateQuery,alphas,betas,prefix,history,deltaAudit,outputAudit{coefficient_pass}); \\
  }}
'''
    source += ''.join(f'{new}_REGISTER_ENTRY({v},{t},{p})\n' for v, t, p in REGISTER)
    source += ''.join(f'#undef {new}_{macro}\n' for macro in
                      ['REGISTER_ENTRY', 'ENTRY', 'THREADS', 'ARGS', 'MEMORY'])
    destination = 'prepared_occupancy.metal' if prepared else 'occupancy.metal'
    (BASE / destination).write_text(source)


if __name__ == '__main__':
    generate(False)
    generate(True)
